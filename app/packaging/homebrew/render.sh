#!/usr/bin/env bash
# Renders the Homebrew tap (opengeos/homebrew-rustgis) for one release: the `unigis` cask
# (the signed and notarized UniGIS.app from the macOS DMGs) and the `unigis-cli` formula
# (the command line tool from the macOS CLI and Linux tarballs).
#
#   packaging/homebrew/render.sh <version> <SHA256SUMS> <tap folder>
#
# Writes <tap>/Casks/unigis.rb and <tap>/Formula/unigis-cli.rb. The checksums come from the
# release's SHA256SUMS. REPO defaults to opengeos/RustGIS.
set -euo pipefail

version="${1:?usage: render.sh <version> <SHA256SUMS> <tap folder>}"
version="${version#v}"
sums="${2:?usage: render.sh <version> <SHA256SUMS> <tap folder>}"
tap="${3:?usage: render.sh <version> <SHA256SUMS> <tap folder>}"
repo="${REPO:-opengeos/RustGIS}"

# Only final releases: a pre-release suffix would make Homebrew treat it as the newest version.
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "not an X.Y.Z version: $version" >&2; exit 1; }
[[ "$repo" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || { echo "REPO is not owner/name: $repo" >&2; exit 1; }

# The checksum of one release file, failing when SHA256SUMS lacks it.
sha() {
  local h
  h="$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")"
  [[ "$h" =~ ^[0-9a-f]{64}$ ]] || { echo "no checksum for $1 in $sums" >&2; return 1; }
  echo "$h"
}

dmg_arm="$(sha "UniGIS-$version-macos-aarch64.dmg")"
dmg_intel="$(sha "UniGIS-$version-macos-x86_64.dmg")"
cli_mac_arm="$(sha "unigis-cli-$version-macos-aarch64.tar.gz")"
cli_mac_intel="$(sha "unigis-cli-$version-macos-x86_64.tar.gz")"
cli_linux_arm="$(sha "UniGIS-$version-linux-aarch64.tar.gz")"
cli_linux_intel="$(sha "UniGIS-$version-linux-x86_64.tar.gz")"

mkdir -p "$tap/Casks" "$tap/Formula"
releases="https://github.com/$repo/releases/download/v#{version}"

# The cask follows Homebrew/homebrew-cask style (a plain desc, the default livecheck), so the same
# file can be submitted there once the repository meets its notability and age rules (#89).
cat > "$tap/Casks/unigis.rb" <<RUBY
# Generated by packaging/homebrew/render.sh in $repo on every release; do not edit by hand.
cask "unigis" do
  arch arm: "aarch64", intel: "x86_64"

  version "$version"
  sha256 arm:   "$dmg_arm",
         intel: "$dmg_intel"

  url "$releases/UniGIS-#{version}-macos-#{arch}.dmg"
  name "UniGIS"
  desc "GIS platform"
  homepage "https://rustgis.app/"

  depends_on macos: :big_sur

  app "UniGIS.app"
  binary "#{appdir}/UniGIS.app/Contents/MacOS/unigis"

  zap trash: [
    "~/Library/Application Support/UniGIS",
    "~/Library/Caches/UniGIS",
    "~/Library/Saved Application State/org.rustgis.RustGIS.savedState",
  ]
end
RUBY

cat > "$tap/Formula/unigis-cli.rb" <<RUBY
# Generated by packaging/homebrew/render.sh in $repo on every release; do not edit by hand.
class UnigisCli < Formula
  desc "Command-line tool and MCP server for the UniGIS geographic information system"
  homepage "https://rustgis.app/"
  version "$version"
  license "Apache-2.0"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "$releases/unigis-cli-#{version}-macos-aarch64.tar.gz"
      sha256 "$cli_mac_arm"
    end
    on_intel do
      url "$releases/unigis-cli-#{version}-macos-x86_64.tar.gz"
      sha256 "$cli_mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$releases/UniGIS-#{version}-linux-aarch64.tar.gz"
      sha256 "$cli_linux_arm"
    end
    on_intel do
      url "$releases/UniGIS-#{version}-linux-x86_64.tar.gz"
      sha256 "$cli_linux_intel"
    end
  end

  def install
    bin.install "unigis"
  end

  test do
    assert_match "project.new", shell_output("#{bin}/unigis commands")
  end
end
RUBY
