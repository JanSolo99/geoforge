//! One-off generator for `src/writer/system_rows.rs`: the fixed rows of
//! GDB_DBTune, GDB_ItemTypes and GDB_ItemRelationshipTypes, taken from an empty
//! geodatabase created by GDAL's OpenFileGDB driver.
use geoforge_core::Value;
fn s(v: &Value) -> String {
    match v {
        Value::String(x) | Value::Guid(x) => format!("{x:?}"),
        Value::SmallInteger(n) => n.to_string(),
        Value::Null => "\"\"".into(),
        other => panic!("{other:?}"),
    }
}
fn main() {
    let dir = std::path::PathBuf::from(std::env::args().nth(1).unwrap());
    let rows = |n: u32| -> Vec<Vec<Value>> {
        geoforge_filegdb::Table::open(dir.join(format!("a{n:08x}")))
            .unwrap()
            .features()
            .map(|f| f.unwrap().attributes)
            .collect()
    };
    println!(
        "//! Fixed rows of new geodatabases' system tables. Generated by\n//! `examples/gen_system_rows.rs` from a geodatabase created by GDAL's OpenFileGDB\n//! driver (MIT). Catalog data: item-type and relationship-type identifiers.\n"
    );
    println!("/// GDB_DBTune: (Keyword, ParameterName, ConfigString).");
    println!("pub const DBTUNE: &[(&str, &str, &str)] = &[");
    for r in rows(2) {
        println!("    ({}, {}, {}),", s(&r[0]), s(&r[1]), s(&r[2]));
    }
    println!("];\n\n/// GDB_ItemTypes: (UUID, ParentTypeID, Name).");
    println!("pub const ITEM_TYPES: &[(&str, &str, &str)] = &[");
    for r in rows(5) {
        println!("    ({}, {}, {}),", s(&r[0]), s(&r[1]), s(&r[2]));
    }
    println!(
        "];\n\n/// GDB_ItemRelationshipTypes: (UUID, OrigItemTypeID, DestItemTypeID, Name,\n/// ForwardLabel, BackwardLabel, IsContainment)."
    );
    println!("pub const RELATIONSHIP_TYPES: &[(&str, &str, &str, &str, &str, &str, i16)] = &[");
    for r in rows(7) {
        println!(
            "    ({}, {}, {}, {}, {}, {}, {}),",
            s(&r[0]),
            s(&r[1]),
            s(&r[2]),
            s(&r[3]),
            s(&r[4]),
            s(&r[5]),
            s(&r[6])
        );
    }
    println!("];");
}
