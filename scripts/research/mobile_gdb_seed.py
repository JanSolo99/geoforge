"""Writes crates/unigis-gpkg/src/mobile_seed.rs: the schema and system rows of an empty
ArcGIS Pro mobile geodatabase, read from two files Create Mobile Geodatabase made one after the
other (black-box output, inspected with Python's sqlite3):

    python3 -I scripts/research/mobile_gdb_seed.py a.geodatabase b.geodatabase

Cells that differ between the two are per-file values: creation times (UTC seconds, as a real,
local seconds, a local ISO time inside XML) and the item UUIDs; they become placeholders filled
in when a geodatabase is created.
"""
import re
import sqlite3
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "crates/unigis-gpkg/src/mobile_seed.rs"
UUID = re.compile(r"^\{[0-9A-F]{8}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{12}\}$")
ISO = re.compile(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d")


def fold(a, b):
    a, b = a.casefold(), b.casefold()
    return (a > b) - (a < b)


def open_db(path):
    db = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    db.create_collation("ICUFOLDCASE", fold)
    return db


def master(db):
    return db.execute("select type, name, tbl_name, rootpage, sql from sqlite_master order by rowid").fetchall()


def ipk(db, table):
    """The INTEGER PRIMARY KEY (rowid alias) column's position, or None."""
    info = db.execute(f'pragma table_info("{table}")').fetchall()
    pks = [c for c in info if c[5]]
    if len(pks) == 1 and pks[0][2].upper() == "INTEGER":
        return pks[0][0]
    return None


def rows(db, table):
    return db.execute(f'select rowid, * from "{table}" order by rowid').fetchall()


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(a_path, b_path):
    a, b = open_db(a_path), open_db(b_path)
    entries = master(a)
    assert [e[:3] for e in entries] == [e[:3] for e in master(b)], "schemas differ"
    utc = a.execute("select registration_date from GDB_TableRegistry limit 1").fetchone()[0]
    out = ["// Generated by scripts/research/mobile_gdb_seed.py from empty mobile geodatabases",
           "// written by ArcGIS Pro 3.7 Create Mobile Geodatabase. Do not edit.",
           "",
           "use crate::mobile::{Entry, V};",
           "",
           "pub(crate) static SCHEMA: &[Entry] = &["]
    uuids = []
    for kind, name, table, root, sql in entries:
        if kind == "table" and root > 0:
            alias = ipk(a, name)
            ra, rb = rows(a, name), rows(b, name)
            assert len(ra) == len(rb), name
            body = []
            for row_a, row_b in zip(ra, rb):
                cells = []
                for k, (x, y) in enumerate(zip(row_a[1:], row_b[1:])):
                    if alias == k:
                        cells.append("V::N")
                    elif x == y:
                        cells.append(constant(x))
                    elif isinstance(x, str) and UUID.match(x):
                        uuids.append(x)
                        cells.append(f"V::Uuid({len(uuids) - 1})")
                    elif isinstance(x, int) and abs(x - utc) <= 5:
                        cells.append("V::Now")
                    elif isinstance(x, int) and abs(x - utc) <= 14 * 3600 + 5:
                        cells.append("V::NowLocal")
                    elif isinstance(x, float) and abs(x - utc) <= 5:
                        cells.append("V::NowReal")
                    elif isinstance(x, str) and ISO.search(x) and ISO.sub("", x) == ISO.sub("", y):
                        cells.append(f"V::LocalTime({rust_str(ISO.sub('{T}', x))})")
                    else:
                        sys.exit(f"unclassified varying cell {name}[{k}]: {x!r} / {y!r}")
                body.append(f"({row_a[0]}, &[{', '.join(cells)}])")
            out.append(f"    Entry::Table {{ name: {rust_str(name)}, sql: {rust_str(sql)}, rows: &[")
            out.extend(f"        {r}," for r in body)
            out.append("    ] },")
        elif kind == "index":
            cols = []
            for seq, cid, col in a.execute(f'pragma index_info("{name}")').fetchall():
                alias = ipk(a, table)
                cols.append(-1 if cid == -1 or cid == alias else cid)
            check_order(a, name, table, cols)
            sql_text = "None" if sql is None else f"Some({rust_str(sql)})"
            out.append(f"    Entry::Index {{ name: {rust_str(name)}, table: {rust_str(table)}, sql: {sql_text}, columns: &{cols} }},")
        else:
            out.append(f"    Entry::Raw {{ kind: {rust_str(kind)}, name: {rust_str(name)}, table: {rust_str(table)}, sql: {rust_str(sql)} }},")
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT} ({len(entries)} schema entries, {len(uuids)} per-file UUIDs)")


def constant(x):
    if x is None:
        return "V::N"
    if isinstance(x, int):
        return f"V::I({x})"
    if isinstance(x, float):
        return f"V::R({x!r}_f64)" if "e" in repr(x) or "." in repr(x) else f"V::R({x!r}.0)"
    if isinstance(x, str):
        return f"V::T({rust_str(x)})"
    return "V::B(&[" + ", ".join(str(c) for c in x) + "])"


def check_order(db, index, table, cols):
    """The writer sorts index keys with the BINARY collation: make sure that is the order the
    index's own collations (NOCASE, ICUFOLDCASE) give for this data."""
    names = [r[1] for r in db.execute(f'pragma table_info("{table}")').fetchall()]
    exprs = ["rowid" if c == -1 else f'"{names[c]}"' for c in cols]
    colls = [r[4] for r in db.execute(f'pragma index_xinfo("{index}")').fetchall() if r[5]]
    data = db.execute(f'select {", ".join(exprs + ["rowid"])} from "{table}"').fetchall()

    def key(fold):
        def k(row):
            out = []
            for v, coll in zip(row, colls + ["BINARY"]):
                if v is None:
                    out.append((0, 0))
                elif isinstance(v, (int, float)):
                    out.append((1, v))
                elif isinstance(v, str):
                    out.append((2, v.casefold() if fold and coll.upper() != "BINARY" else v))
                else:
                    out.append((3, v))
            return tuple(out)
        return k
    if sorted(data, key=key(True)) != sorted(data, key=key(False)):
        sys.exit(f"index {index}: collated order differs from binary order")


if __name__ == "__main__":
    main(*sys.argv[1:3])
