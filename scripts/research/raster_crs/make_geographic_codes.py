"""Regenerate the pure-Rust geographic EPSG classification from public PROJ data.

No runtime database dependency is added. See https://proj.org/en/stable/resource_files.html#proj-db
"""
import argparse
import sqlite3
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('database', nargs='?', default='/usr/share/proj/proj.db')
args = parser.parse_args()
connection = sqlite3.connect(Path(args.database).resolve().as_uri() + '?mode=ro', uri=True)
version = dict(connection.execute("SELECT key,value FROM metadata WHERE key LIKE 'EPSG.%'"))
codes = [int(row[0]) for row in connection.execute("SELECT code FROM geodetic_crs WHERE auth_name='EPSG' AND type IN ('geographic 2D','geographic 3D')")]
codes = sorted(set(codes))
text = '// Generated by scripts/research/raster_crs/make_geographic_codes.py\n'
text += '// Public PROJ proj.db / EPSG ' + version['EPSG.VERSION'] + ', ' + version['EPSG.DATE'] + '.\n'
text += '// Geographic 2D and 3D identifiers; no runtime PROJ/GDAL dependency.\n'
text += 'pub(crate) const GEOGRAPHIC_EPSG: &[u32] = &[\n'
for start in range(0, len(codes), 12):
    text += '    ' + ', '.join(map(str, codes[start:start + 12])) + ',\n'
text += '];\n'
Path('crates/unigis-raster/src/geographic_crs.rs').write_text(text)
print('Generated',len(codes),'codes; highest',max(codes))
